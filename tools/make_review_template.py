#!/usr/bin/env python3
"""Turns tools/review_page.html into src/core/ReviewPageTemplate.inc (a list of string pieces, each small enough for MSVC's string-literal limit)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'review_page.html'), 'rb').read()
text = src.decode('ascii')            # the page is pure ASCII on purpose
assert ')HTMLX"' not in text
lines = text.split('\n')
pieces, cur = [], ''
for ln in lines:
    if len(cur) + len(ln) + 1 > 6000 and cur:
        pieces.append(cur); cur = ''
    cur += ln + '\n'
pieces.append(cur)
out = ['// Generated by tools/make_review_template.py from tools/review_page.html. Do not edit by hand.',
       'static const char* const kReviewTemplate[] = {']
for p in pieces:
    out.append('R"HTMLX(' + p + ')HTMLX",')
out.append('};')
open(os.path.join(here, '..', 'src', 'core', 'ReviewPageTemplate.inc'), 'w', newline='\n').write('\n'.join(out) + '\n')
print(len(pieces), 'pieces,', len(text), 'bytes')
