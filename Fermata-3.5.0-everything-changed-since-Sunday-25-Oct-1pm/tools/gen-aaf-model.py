#!/usr/bin/env python3
"""Generates src/core/AafModel.h: the part of the AAF class and type dictionary that Fermata's AAF export writes into
its files (an AAF carries definitions of every class and type it uses). The tables are taken from pyaaf2's model
(https://github.com/markreidvfx/pyaaf2, MIT licence), which transcribes the SMPTE AAF object specification.
Usage: tools/gen-aaf-model.py /path/to/pyaaf2/src > src/core/AafModel.h
The output is the closure of the classes named in SEEDS: every one of their ancestors and all their properties, the
types of those properties, and every class and type those types refer to."""
import sys, importlib.util
src = sys.argv[1]
def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path); m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m
classdefs = load('classdefs', src + '/aaf2/model/classdefs.py')
typedefs = load('typedefs', src + '/aaf2/model/typedefs.py')
classes = dict(classdefs.classdefs)
# the root class and its two types (the compound file's root object), from pyaaf2's metadict.py
classes['Root'] = ('b3b398a5-1c90-11d4-8053-080036210804', None, True, {
    "Header"         : ('0d010301-0102-0100-060e-2b3401010102', 0x0002, '05022800-0000-0000-060e-2b3401040101', False, False),
    "MetaDictionary" : ('0d010301-0101-0100-060e-2b3401010102', 0x0001, '05022700-0000-0000-060e-2b3401040101', False, False)})
strongrefs = dict(typedefs.strongrefs)
strongrefs['HeaderStrongRefence'] = ('05022800-0000-0000-060e-2b3401040101', '0d010101-0101-2f00-060e-2b3402060101')
strongrefs['MetaDictionaryStrongReference'] = ('05022700-0000-0000-060e-2b3401040101', '0d010101-0225-0000-060e-2b3402060101')

def norm(a): return a.lower()
byauid = {norm(v[0]): k for k, v in classes.items()}
# every typedef: auid -> (kind, name, args)
types = {}
def add(kind, table):
    for name, args in table.items():
        if not isinstance(args, (tuple, list)): args = (args,)
        types[norm(args[0])] = (kind, name, args)
add('Int', typedefs.ints); add('Enum', typedefs.enums); add('Record', typedefs.records); add('FixedArray', typedefs.fixed_arrays)
add('VarArray', typedefs.var_arrays); add('Rename', typedefs.renames); add('String', typedefs.strings); add('Stream', typedefs.streams)
add('Opaque', typedefs.opaques); add('ExtEnum', typedefs.extenums); add('Character', typedefs.chars); add('Indirect', typedefs.indirects)
add('Set', typedefs.sets); add('StrongRef', strongrefs); add('WeakRef', typedefs.weakrefs)

SEEDS = ['Root', 'Header', 'MetaDictionary', 'ClassDefinition', 'PropertyDefinition',
         'TypeDefinitionInteger', 'TypeDefinitionEnumeration', 'TypeDefinitionRecord', 'TypeDefinitionFixedArray', 'TypeDefinitionVariableArray',
         'TypeDefinitionRename', 'TypeDefinitionString', 'TypeDefinitionStream', 'TypeDefinitionOpaque', 'TypeDefinitionExtendibleEnumeration',
         'TypeDefinitionCharacter', 'TypeDefinitionIndirect', 'TypeDefinitionSet', 'TypeDefinitionStrongObjectReference', 'TypeDefinitionWeakObjectReference',
         'ContentStorage', 'Dictionary', 'Identification', 'CompositionMob', 'MasterMob', 'SourceMob', 'TimelineMobSlot',
         'Sequence', 'SourceClip', 'Filler', 'Timecode', 'Transition', 'OperationGroup',
         'WAVEDescriptor', 'SoundDescriptor', 'NetworkLocator', 'DataDefinition', 'OperationDefinition', 'ContainerDefinition']
wanted_classes, wanted_types = set(), set()
def want_type(auid):
    auid = norm(auid)
    if auid in wanted_types or auid not in types: return
    wanted_types.add(auid)
    kind, name, args = types[auid]
    if kind in ('Enum', 'Rename', 'String', 'FixedArray', 'VarArray', 'Set'): want_type(args[1])
    elif kind == 'Record':
        for _, t in args[1]: want_type(t)
    elif kind in ('StrongRef', 'WeakRef'): want_class_by_auid(args[1])
def want_class_by_auid(auid):
    auid = norm(auid)
    if auid in byauid: want_class(byauid[auid])
def want_class(name):
    if name in wanted_classes: return
    wanted_classes.add(name)
    cauid, parent, concrete, props = classes[name]
    if parent: want_class_by_auid(parent)
    for pname, (pauid, pid, tauid, optional, unique) in props.items():
        if pid is not None: want_type(tauid)
for s in SEEDS: want_class(s)
# (a property with no fixed pid is an extension the SMPTE registry gives a dynamic id; the export never writes one, so they are left out)
def fixed(props): return [(n, a) for n, a in props.items() if a[1] is not None]
# tidy, deterministic order
cl = sorted(wanted_classes, key=lambda n: norm(classes[n][0]))
ty = sorted(wanted_types)
out = []
w = out.append
w('// GENERATED by tools/gen-aaf-model.py from pyaaf2\'s transcription of the AAF object specification: do not edit by hand.')
w('// The classes and types Fermata\'s AAF export writes into its files\' dictionary (AafWrite.cpp): %d classes, %d types.' % (len(cl), len(ty)))
w('#pragma once'); w('#include <cstdint>'); w(''); w('namespace td::aafmodel'); w('{')
w('struct PropDef { const char* name; const char* auid; std::uint16_t pid; const char* type; bool optional; bool unique; };')
w('struct ClassDef { const char* name; const char* auid; const char* parent; bool concrete; const PropDef* props; int numProps; };')
w('enum class TypeKind { Int, Enum, Record, FixedArray, VarArray, Rename, String, Stream, Opaque, ExtEnum, Character, Indirect, Set, StrongRef, WeakRef };')
w('struct TypeDef')
w('{')
w('    const char* name; const char* auid; TypeKind kind;')
w('    const char* ref;                   // the element / renamed / referenced type (a class for StrongRef and WeakRef); nullptr when none')
w('    int size; bool isSigned;           // Int: the size in bytes; FixedArray: the element count')
w('    const char* const* names; int numNames;        // Enum, ExtEnum: the element names; Record: the member names')
w('    const std::int64_t* values;        // Enum: the element values')
w('    const char* const* auids; int numAuids;        // ExtEnum: the element auids; Record: the member types; WeakRef: the target set (property auids)')
w('};')
w('')
for name in cl:
    cauid, parent, concrete, props = classes[name]
    if fixed(props):
        w('static const PropDef props_%s[] = {' % name)
        for pname, (pauid, pid, tauid, optional, unique) in fixed(props):
            w('    { "%s", "%s", 0x%04x, "%s", %s, %s },' % (pname, norm(pauid), pid, norm(tauid), 'true' if optional else 'false', 'true' if unique else 'false'))
        w('};')
w('')
w('static const ClassDef classes[] = {')
for name in cl:
    cauid, parent, concrete, props = classes[name]
    w('    { "%s", "%s", %s, %s, %s, %d },' % (name, norm(cauid), ('"%s"' % norm(parent)) if parent else 'nullptr', 'true' if concrete else 'false', ('props_%s' % name) if fixed(props) else 'nullptr', len(fixed(props))))
w('};')
w('')
def cname(auid): return 't_' + auid.replace('-', '_')
for auid in ty:
    kind, name, args = types[auid]
    if kind == 'Enum':
        items = sorted(args[2].items())
        w('static const char* const %s_names[] = { %s };' % (cname(auid), ', '.join('"%s"' % n for _, n in items)))
        w('static const std::int64_t %s_values[] = { %s };' % (cname(auid), ', '.join(str(v) for v, _ in items)))
    elif kind == 'ExtEnum':
        items = sorted(args[1].items(), key=lambda kv: kv[1])
        w('static const char* const %s_names[] = { %s };' % (cname(auid), ', '.join('"%s"' % n for _, n in items)))
        w('static const char* const %s_auids[] = { %s };' % (cname(auid), ', '.join('"%s"' % norm(a) for a, _ in items)))
    elif kind == 'Record':
        w('static const char* const %s_names[] = { %s };' % (cname(auid), ', '.join('"%s"' % n for n, _ in args[1])))
        w('static const char* const %s_auids[] = { %s };' % (cname(auid), ', '.join('"%s"' % norm(t) for _, t in args[1])))
    elif kind == 'WeakRef':
        w('static const char* const %s_auids[] = { %s };' % (cname(auid), ', '.join('"%s"' % norm(t) for t in args[2])))
w('')
w('static const TypeDef types[] = {')
for auid in ty:
    kind, name, args = types[auid]
    ref = 'nullptr'; size = 0; signed = 'false'; names = 'nullptr'; nn = 0; values = 'nullptr'; auids = 'nullptr'; na = 0
    if kind == 'Int': size = args[1]; signed = 'true' if args[2] else 'false'
    elif kind in ('Rename', 'String', 'VarArray', 'Set', 'StrongRef', 'WeakRef'): ref = '"%s"' % norm(args[1])
    elif kind == 'FixedArray': ref = '"%s"' % norm(args[1]); size = args[2]
    elif kind == 'Enum': ref = '"%s"' % norm(args[1]); names = cname(auid) + '_names'; nn = len(args[2]); values = cname(auid) + '_values'
    elif kind == 'ExtEnum': names = cname(auid) + '_names'; nn = len(args[1]); auids = cname(auid) + '_auids'; na = len(args[1])
    elif kind == 'Record': names = cname(auid) + '_names'; nn = len(args[1]); auids = cname(auid) + '_auids'; na = len(args[1])
    if kind == 'WeakRef': auids = cname(auid) + '_auids'; na = len(args[2])
    w('    { "%s", "%s", TypeKind::%s, %s, %d, %s, %s, %d, %s, %s, %d },' % (name, auid, kind, ref, size, signed, names, nn, values, auids, na))
w('};')
w('} // namespace td::aafmodel')
print('\n'.join(out))
print('closure: %d classes, %d types' % (len(cl), len(ty)), file=sys.stderr)
